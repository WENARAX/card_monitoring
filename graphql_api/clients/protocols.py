from typing import Protocol

from services.access.models import AuditRecord, User
from services.cards.models import Block, Card, Client, Holder
from services.incidents.models import Decision, Incident
from services.operations.models import AuthRequest, DictionaryItem, Operation
from services.risk.models import Assessment, Rule, RuleHit, Threshold


class CardsClient(Protocol):
    def list_clients(self) -> list[Client]: ...
    def get_client(self, client_id: int) -> Client: ...
    def list_holders(self, client_id: int | None = None) -> list[Holder]: ...
    def get_holder(self, holder_id: int) -> Holder: ...
    def list_cards(self, holder_id: int | None = None) -> list[Card]: ...
    def get_card(self, card_id: int) -> Card: ...
    def list_blocks(self, card_id: int) -> list[Block]: ...


class OperationsClient(Protocol):
    def list_channels(self) -> list[DictionaryItem]: ...
    def get_channel(self, item_id: int) -> DictionaryItem: ...
    def list_countries(self) -> list[DictionaryItem]: ...
    def get_country(self, item_id: int) -> DictionaryItem: ...
    def list_categories(self) -> list[DictionaryItem]: ...
    def get_category(self, item_id: int) -> DictionaryItem: ...
    def list_auth_requests(self) -> list[AuthRequest]: ...
    def get_auth_request(self, request_id: int) -> AuthRequest: ...
    def find_operation_by_auth_request(self, request_id: int) -> Operation | None: ...
    def list_operations(self) -> list[Operation]: ...
    def get_operation(self, operation_id: int) -> Operation: ...


class RiskClient(Protocol):
    def list_rules(self) -> list[Rule]: ...
    def get_rule(self, rule_id: int) -> Rule: ...
    def list_assessments(self) -> list[Assessment]: ...
    def get_assessment(self, assessment_id: int) -> Assessment: ...
    def find_assessment(self, subject_type: str, subject_id: int) -> Assessment | None: ...
    def list_hits(self, assessment_id: int) -> list[RuleHit]: ...
    def current_threshold(self) -> Threshold: ...


class IncidentsClient(Protocol):
    def list_incidents(self) -> list[Incident]: ...
    def get_incident(self, incident_id: int) -> Incident: ...
    def list_decisions(self, incident_id: int) -> list[Decision]: ...
    def get_decision(self, decision_id: int) -> Decision: ...


class AccessClient(Protocol):
    def list_users(self) -> list[User]: ...
    def get_user(self, user_id: int) -> User: ...
    def list_audit(self, user_id: int | None = None) -> list[AuditRecord]: ...
